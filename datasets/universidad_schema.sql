DROP TABLE IF EXISTS matriculas CASCADE;
DROP TABLE IF EXISTS prerrequisitos CASCADE;
DROP TABLE IF EXISTS cursos CASCADE;
DROP TABLE IF EXISTS estudiantes CASCADE;
DROP TABLE IF EXISTS profesores CASCADE;
DROP TABLE IF EXISTS departamentos CASCADE;

CREATE TABLE departamentos (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(100) NOT NULL UNIQUE,
    edificio VARCHAR(50)  NOT NULL
);

CREATE TABLE profesores (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(60)  NOT NULL,
    apellido        VARCHAR(60)  NOT NULL,
    email           VARCHAR(120) NOT NULL UNIQUE,
    id_departamento INT          NOT NULL
        REFERENCES departamentos(id) ON DELETE RESTRICT
);

CREATE TABLE estudiantes (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(60)  NOT NULL,
    apellido         VARCHAR(60)  NOT NULL,
    email            VARCHAR(120) NOT NULL UNIQUE,
    fecha_nacimiento DATE         NOT NULL,
    ciudad           VARCHAR(60)  NOT NULL,
    CONSTRAINT chk_nacimiento CHECK (fecha_nacimiento < DATE '2010-01-01')
);

CREATE TABLE cursos (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(12)  NOT NULL UNIQUE,
    nombre          VARCHAR(120) NOT NULL,
    creditos        SMALLINT     NOT NULL CHECK (creditos BETWEEN 1 AND 10),
    id_profesor     INT
        REFERENCES profesores(id) ON DELETE SET NULL,
    id_departamento INT NOT NULL
        REFERENCES departamentos(id) ON DELETE RESTRICT
);

CREATE TABLE prerrequisitos (
    id_curso         INT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
    id_prerrequisito INT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
    PRIMARY KEY (id_curso, id_prerrequisito),
    CONSTRAINT chk_prerrequisito_distinto CHECK (id_curso <> id_prerrequisito)
);

CREATE TABLE matriculas (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante   INT NOT NULL REFERENCES estudiantes(id) ON DELETE CASCADE,
    id_curso        INT NOT NULL REFERENCES cursos(id) ON DELETE CASCADE,
    semestre        VARCHAR(10) NOT NULL,
    nota            NUMERIC(3,1) CHECK (nota BETWEEN 0.0 AND 5.0),
    fecha_matricula DATE NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (id_estudiante, id_curso, semestre)
);

CREATE INDEX idx_matriculas_estudiante ON matriculas(id_estudiante);
CREATE INDEX idx_matriculas_curso      ON matriculas(id_curso);
CREATE INDEX idx_cursos_profesor       ON cursos(id_profesor);
CREATE INDEX idx_cursos_departamento   ON cursos(id_departamento);
