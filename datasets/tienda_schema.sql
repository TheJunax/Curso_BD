-- ============================================================
-- Dataset: Tienda
-- Esquema (PostgreSQL 16)
-- ============================================================

DROP TABLE IF EXISTS detalle_pedido CASCADE;
DROP TABLE IF EXISTS pedidos CASCADE;
DROP TABLE IF EXISTS productos CASCADE;
DROP TABLE IF EXISTS categorias CASCADE;
DROP TABLE IF EXISTS proveedores CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;

CREATE TABLE categorias (
    id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE proveedores (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(100) NOT NULL,
    ciudad   VARCHAR(60)  NOT NULL,
    telefono VARCHAR(20)
);

CREATE TABLE productos (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120)   NOT NULL,
    precio        NUMERIC(10,2)  NOT NULL CHECK (precio >= 0),
    stock         INT            NOT NULL DEFAULT 0 CHECK (stock >= 0),
    id_categoria  INT            NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT,
    id_proveedor  INT            REFERENCES proveedores(id) ON DELETE SET NULL
);

CREATE TABLE clientes (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(60)  NOT NULL,
    apellido       VARCHAR(60)  NOT NULL,
    email          VARCHAR(120) NOT NULL UNIQUE,
    ciudad         VARCHAR(60)  NOT NULL,
    fecha_registro DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE pedidos (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
    fecha      DATE NOT NULL DEFAULT CURRENT_DATE,
    estado     VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'enviado', 'entregado', 'cancelado')),
    total      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0)
);

CREATE TABLE detalle_pedido (
    id_pedido       INT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    id_producto     INT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    cantidad        INT NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    PRIMARY KEY (id_pedido, id_producto)
);

CREATE INDEX idx_pedidos_cliente    ON pedidos(id_cliente);
CREATE INDEX idx_pedidos_fecha      ON pedidos(fecha);
CREATE INDEX idx_productos_categoria ON productos(id_categoria);
CREATE INDEX idx_productos_proveedor ON productos(id_proveedor);
CREATE INDEX idx_detalle_producto   ON detalle_pedido(id_producto);
