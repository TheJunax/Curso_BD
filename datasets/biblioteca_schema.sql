DROP TABLE IF EXISTS prestamos CASCADE;
DROP TABLE IF EXISTS ejemplares CASCADE;
DROP TABLE IF EXISTS libros CASCADE;
DROP TABLE IF EXISTS autores CASCADE;
DROP TABLE IF EXISTS socios CASCADE;

CREATE TABLE autores (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    nacionalidad VARCHAR(60)
);

CREATE TABLE libros (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn     VARCHAR(20)  NOT NULL UNIQUE,
    titulo   VARCHAR(150) NOT NULL,
    anio     SMALLINT     NOT NULL CHECK (anio BETWEEN 1400 AND 2100),
    id_autor INT          NOT NULL REFERENCES autores(id) ON DELETE RESTRICT
);

CREATE TABLE ejemplares (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro INT NOT NULL REFERENCES libros(id) ON DELETE CASCADE,
    codigo   VARCHAR(20) NOT NULL UNIQUE,
    estado   VARCHAR(20) NOT NULL DEFAULT 'disponible'
        CHECK (estado IN ('disponible', 'prestado', 'dañado', 'perdido'))
);

CREATE TABLE socios (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(60)  NOT NULL,
    apellido   VARCHAR(60)  NOT NULL,
    email      VARCHAR(120) NOT NULL UNIQUE,
    ciudad     VARCHAR(60)  NOT NULL,
    fecha_alta DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE prestamos (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejemplar      INT  NOT NULL REFERENCES ejemplares(id) ON DELETE RESTRICT,
    id_socio         INT  NOT NULL REFERENCES socios(id) ON DELETE RESTRICT,
    fecha_prestamo   DATE NOT NULL,
    fecha_devolucion DATE,
    estado           VARCHAR(20) NOT NULL DEFAULT 'activo'
        CHECK (estado IN ('activo', 'devuelto', 'vencido')),
    CONSTRAINT chk_fechas CHECK (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_prestamo)
);

CREATE INDEX idx_libros_autor       ON libros(id_autor);
CREATE INDEX idx_ejemplares_libro   ON ejemplares(id_libro);
CREATE INDEX idx_prestamos_socio    ON prestamos(id_socio);
CREATE INDEX idx_prestamos_ejemplar ON prestamos(id_ejemplar);
CREATE INDEX idx_prestamos_estado   ON prestamos(estado);
