DROP TABLE IF EXISTS equipos, tickets, tecnicos, pagos, facturas,
                     contratos, clientes, planes, barrios CASCADE;

-- ------------------------- ESTRUCTURA --------------------------------
CREATE TABLE barrios (
  id_barrio   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(60) NOT NULL UNIQUE,
  comuna      VARCHAR(40) NOT NULL
);

CREATE TABLE planes (
  id_plan         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(40) NOT NULL UNIQUE,
  velocidad_mbps  INT NOT NULL CHECK (velocidad_mbps > 0),
  precio_mensual  NUMERIC(10,2) NOT NULL CHECK (precio_mensual >= 0),
  tipo            VARCHAR(12) NOT NULL DEFAULT 'Hogar'
                  CHECK (tipo IN ('Hogar','Empresarial'))
);

CREATE TABLE clientes (
  id_cliente      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cedula          VARCHAR(15) NOT NULL UNIQUE,
  nombres         VARCHAR(60) NOT NULL,
  apellidos       VARCHAR(60) NOT NULL,
  email           VARCHAR(100),
  telefono        VARCHAR(15) NOT NULL,
  estrato         SMALLINT NOT NULL CHECK (estrato BETWEEN 1 AND 6),
  id_barrio       INT REFERENCES barrios(id_barrio),
  fecha_registro  DATE NOT NULL,
  saldo_favor     NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (saldo_favor >= 0)
);

CREATE TABLE contratos (
  id_contrato   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente    INT NOT NULL REFERENCES clientes(id_cliente),
  id_plan       INT NOT NULL REFERENCES planes(id_plan),
  fecha_inicio  DATE NOT NULL,
  fecha_fin     DATE,
  estado        VARCHAR(10) NOT NULL DEFAULT 'Activo'
                CHECK (estado IN ('Activo','Suspendido','Cancelado')),
  ip_asignada   VARCHAR(15) UNIQUE
);

CREATE TABLE facturas (
  id_factura        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contrato       INT NOT NULL REFERENCES contratos(id_contrato),
  periodo           DATE NOT NULL,          -- primer dia del mes facturado
  fecha_emision     DATE NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  valor             NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
  estado            VARCHAR(10) NOT NULL DEFAULT 'Pendiente'
                    CHECK (estado IN ('Pendiente','Pagada','Vencida')),
  UNIQUE (id_contrato, periodo)
);

CREATE TABLE pagos (
  id_pago     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_factura  INT NOT NULL REFERENCES facturas(id_factura),
  fecha_pago  DATE NOT NULL,
  valor       NUMERIC(10,2) NOT NULL CHECK (valor > 0),
  medio       VARCHAR(10) NOT NULL CHECK (medio IN ('Efectivo','PSE','Tarjeta','Nequi'))
);

CREATE TABLE tecnicos (
  id_tecnico     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(80) NOT NULL,
  especialidad   VARCHAR(12) NOT NULL
                 CHECK (especialidad IN ('Fibra','Radioenlace','Soporte','Redes')),
  salario        NUMERIC(10,2) NOT NULL,
  id_supervisor  INT REFERENCES tecnicos(id_tecnico)
);

CREATE TABLE tickets (
  id_ticket       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_contrato     INT NOT NULL REFERENCES contratos(id_contrato),
  id_tecnico      INT REFERENCES tecnicos(id_tecnico),  -- NULL = sin asignar
  fecha_apertura  TIMESTAMP NOT NULL,
  fecha_cierre    TIMESTAMP,                            -- NULL = abierto
  categoria       VARCHAR(15) NOT NULL CHECK (categoria IN
                  ('Sin servicio','Lentitud','Intermitencia','Traslado','Facturacion')),
  prioridad       VARCHAR(5) NOT NULL CHECK (prioridad IN ('Baja','Media','Alta')),
  descripcion     VARCHAR(200)
);

CREATE TABLE equipos (
  id_equipo    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  serial       VARCHAR(20) NOT NULL UNIQUE,
  modelo       VARCHAR(40) NOT NULL,
  tipo         VARCHAR(6) NOT NULL CHECK (tipo IN ('ONT','Router','Antena')),
  estado       VARCHAR(10) NOT NULL DEFAULT 'Bodega'
               CHECK (estado IN ('Bodega','Instalado','Danado')),
  id_contrato  INT REFERENCES contratos(id_contrato)
);

